#!/bin/bash
# Writes the Hammerhead client secret from the build setting HAMMERHEAD_CLIENT_SECRET (Config/Secrets.xcconfig)
# into a generated Swift file. The secret is XOR-masked with a fresh random key per build, so it never appears
# as plain text in the binary, in Info.plist or in the repository. Masking only slows down extraction.
# Without a secret the file is still generated and the app hides Hammerhead.
set -euo pipefail

out="$1"
secret="${HAMMERHEAD_CLIENT_SECRET:-}"

masked=""
mask=""
if [ -n "$secret" ]; then
    read -r -a bytes <<< "$(printf '%s' "$secret" | od -An -tu1 -v | tr -s ' \n' '  ')"
    read -r -a keys <<< "$(head -c "${#bytes[@]}" /dev/urandom | od -An -tu1 -v | tr -s ' \n' '  ')"
    for i in "${!bytes[@]}"; do
        masked+="$(( bytes[i] ^ keys[i] )), "
        mask+="${keys[i]}, "
    done
fi

cat > "$out" <<EOF
// Generated by scripts/hammerhead-secret.sh at build time. Do not edit or commit.
enum HammerheadSecret {
    private static let masked: [UInt8] = [${masked%, }]
    private static let mask: [UInt8] = [${mask%, }]

    static var isAvailable: Bool { !masked.isEmpty }

    /// Unmasked only for the request that needs it; nil when the build has no secret.
    static func value() -> String? {
        masked.isEmpty ? nil : String(decoding: zip(masked, mask).map { \$0 ^ \$1 }, as: UTF8.self)
    }
}
EOF
